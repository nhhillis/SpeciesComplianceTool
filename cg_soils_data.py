def _normalize(sym: str) -> str:
    """Strip leading zeros from MLRA symbol for consistent lookup."""
    return sym.lstrip("0") if sym else sym


def lookup(mlra_sym: str) -> list[dict] | None:
    """Return list of C&G associations for a given MLRA symbol, or None if not found."""
    return CG_SOILS.get(_normalize(mlra_sym))
